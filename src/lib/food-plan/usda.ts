export function usdaUrl(fdcId: number): string {
  return `${FDC}/${fdcId}/nutrients`;
}

export function scaleFood(foodItem: UsdaFood, servings: number): ScaledFood {
  const grams = foodItem.grams * servings;
  const factor = grams / 100;
  const per = foodItem.per100g;
  return {
    grams,
    kcal: per.kcal * factor,
    protein: per.protein * factor,
    fiber: per.fiber === null ? null : per.fiber * factor,
    sat: per.sat === null ? null : per.sat * factor,
    sodium: per.sodium === null ? null : per.sodium * factor,
    calcium: per.calcium === null ? null : per.calcium * factor,
  };
}

export function round1(value: number): number {
  return Math.round(value * 10) / 10;
}

export function formatAmount(value: number | null, digits = 1): string {
  if (value === null) return "not reported";
  return round1(value).toFixed(digits);
}

export function allowsPattern(item: UsdaFood, pattern: DietPattern | ""): boolean {
  if (!pattern || pattern === "omnivore") return true;
  if (pattern === "vegan") return item.kind === "plant";
  if (pattern === "vegetarian") return item.kind === "plant" || item.kind === "egg" || item.kind === "dairy";
  return item.kind !== "meat";
}

export function blockedByAllergy(item: UsdaFood, allergens: readonly string[], dairyFree: boolean): boolean {
  if (dairyFree && item.kind === "dairy") return true;
  return item.allergens.some((allergen) => allergens.includes(allergen));
}

