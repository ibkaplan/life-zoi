/**
 * Greek input for LifeZoi Mind's rule-based conversation. It works like `ru-cues.ts`:
 * recognizable Greek wording becomes short English keywords that the conversation's
 * English patterns already read. Safety checks never use these cues.
 *
 * Patterns run on lower-case text without accents, with final ς written as σ, so
 * "Φοβάμαι" and "φοβαμαι" read the same. `S` marks the start of a word and `E` its
 * end, because `\b` does not work with Greek letters.
 */

const L = "α-ω";
const S = `(?<![${L}])`;
const E = `(?![${L}])`;

type Cue = readonly [RegExp, string];

