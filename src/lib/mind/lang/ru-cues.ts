/**
 * Russian input for LifeZoi Mind's rule-based conversation.
 *
 * The conversation recognizes situations with English patterns. For a Russian message,
 * these cues turn recognizable Russian wording into short English keywords ("my mom",
 * "is sick", "can't sleep"), and the conversation reads those keywords instead. Safety
 * checks never use these cues: they read the person's own words (see `safety.ts`).
 *
 * Patterns run on lower-case text with "ё" replaced by "е". `S` marks the start of a word,
 * because `\b` does not work with Cyrillic letters in JavaScript.
 */

const S = "(?<![а-я])";
const E = "(?![а-я])";

/** A cue: a Russian pattern and the English keywords it stands for. */
type Cue = readonly [RegExp, string];

const cue = (pattern: string, english: string): Cue => [new RegExp(pattern, "u"), english];
const stems = (list: string, english: string): Cue => cue(`${S}(?:${list})`, english);
const words = (list: string, english: string): Cue => cue(`${S}(?:${list})${E}`, english);

