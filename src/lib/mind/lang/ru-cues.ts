function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

/**
 * English keywords for a Russian message. Messages without Cyrillic letters are returned
 * as they are, so a person who writes in English on the Russian page is still understood.
 */
export function russianCues(text: string): string {
  if (!/[а-яё]/i.test(text)) return text;
  const value = normalize(text);
  const found: string[] = [];
  const short = value.split(" ").length <= 5;
  for (const [pattern, english] of WHOLE) if (pattern.test(value) && (english !== "yes" || short)) found.push(english);
  for (const [pattern, english] of PEOPLE)
    if (pattern.test(value)) {
      found.push(english);
      break;
    }
  for (const [pattern, english] of SITUATIONS) if (pattern.test(value) && !found.includes(english)) found.push(english);
  return found.join(", ");
}
