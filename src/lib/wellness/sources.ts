export type WellnessSourceId = (typeof wellnessSources)[number]["id"];

const byId = new Map<string, SourceRecord>(wellnessSources.map((source) => [source.id, source]));

export function sourceById(id: string): SourceRecord | undefined {
  return byId.get(id);
}

export function sourcesByIds(ids: readonly string[]): SourceRecord[] {
  return ids.flatMap((id) => {
    const source = byId.get(id);
    return source ? [source] : [];
  });
}

