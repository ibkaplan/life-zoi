import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { isPublicPath } from "@/lib/auth/public-paths";
import { MANIFEST_PATH, OFFLINE_PATH, PRECACHE_FILES, SERVICE_WORKER_PATH } from "@/lib/pwa/config";
import manifest from "@/app/manifest";

const PUBLIC = join(process.cwd(), "public");
const sw = readFileSync(join(PUBLIC, "sw.js"), "utf8");

function swPrecacheList(): string[] {
  const match = sw.match(/const PRECACHE_FILES = (\[[\s\S]*?\]);/);
  expect(match, "public/sw.js declares PRECACHE_FILES").not.toBeNull();
  return JSON.parse(match![1].replace(/,\s*\]$/, "]"));
}

describe("installable app: the service worker keeps nothing private", () => {
  it("precaches exactly the public shell files listed in config", () => {
    expect(swPrecacheList()).toEqual([...PRECACHE_FILES]);
  });

  it("precaches only public files that exist and open without signing in", () => {
    for (const path of PRECACHE_FILES) {
      expect(isPublicPath(path), path).toBe(true);
      if (path === MANIFEST_PATH) continue; // generated by src/app/manifest.ts
      expect(() => readFileSync(join(PUBLIC, path)), path).not.toThrow();
    }
    expect(PRECACHE_FILES.some((path) => path.startsWith("/api"))).toBe(false);
  });

  it("never writes a response into the cache at run time", () => {
    // Only install() fills the cache, with PRECACHE_FILES. No page or API answer is stored.
    expect(sw).not.toMatch(/\.put\(/);
    expect(sw).toContain("cache.addAll(PRECACHE_FILES");
  });

  it("answers page loads from the network, with the offline page only as a fallback", () => {
    expect(sw).toContain('request.mode === "navigate"');
    expect(sw).toMatch(/fetch\(request\)\.catch\(/);
    expect(sw).toContain(`const OFFLINE_PATH = "${OFFLINE_PATH}"`);
  });

  it("leaves other sites and non-GET requests alone", () => {
    expect(sw).toContain('if (request.method !== "GET") return;');
    expect(sw).toContain("if (url.origin !== self.location.origin) return;");
  });

  it("serves the worker, manifest, offline page and icons to visitors", () => {
    expect(isPublicPath(SERVICE_WORKER_PATH)).toBe(true);
    expect(isPublicPath(MANIFEST_PATH)).toBe(true);
    expect(isPublicPath(OFFLINE_PATH)).toBe(true);
    expect(isPublicPath("/icons/icon-512.png")).toBe(true);
    expect(isPublicPath("/sw.js/extra")).toBe(false);
    expect(isPublicPath("/offline")).toBe(false);
  });

  it("describes an installable app with any and maskable icons", () => {
    const m = manifest();
    expect(m.start_url).toBe("/");
    expect(m.display).toBe("standalone");
    expect(m.icons?.some((icon) => icon.sizes === "512x512" && icon.purpose === "maskable")).toBe(true);
    expect(m.icons?.some((icon) => icon.sizes === "192x192")).toBe(true);
    for (const icon of m.icons ?? []) {
      expect(() => readFileSync(join(PUBLIC, icon.src))).not.toThrow();
    }
  });

  it("keeps the offline page free of personal details and in all four languages", () => {
    const html = readFileSync(join(PUBLIC, "offline.html"), "utf8");
    for (const lang of ["en:", "uk:", "ru:", "el:"]) expect(html).toContain(lang);
    expect(html).not.toMatch(/fetch\(|supabase|\/api\//i);
  });
});
